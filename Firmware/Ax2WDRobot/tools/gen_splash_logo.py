"""Converts data/image/ax_claim_white.png into a 128x64 1-bit splash bitmap (src/SplashLogo.h)."""
import os
from PIL import Image

W, H = 128, 64
project_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = Image.open(os.path.join(project_dir, 'data', 'image', 'ax_claim_white.png')).convert('RGBA')

alpha = src.getchannel('A')
# Keep only the wordmark: the tagline below it is unreadable at 128x64
alpha = alpha.crop((0, 0, alpha.width, 670))
alpha = alpha.crop(alpha.getbbox())
scale = (W - 4) / alpha.width
size = (W - 4, max(1, round(alpha.height * scale)))
alpha = alpha.resize(size, Image.LANCZOS)

canvas = Image.new('1', (W, H), 0)
mask = alpha.point(lambda a: 255 if a > 90 else 0).convert('1')
canvas.paste(1, ((W - size[0]) // 2, (H - size[1]) // 2 - 6), mask)

data = bytearray()
for y in range(H):
    for xb in range(W // 8):
        b = 0
        for bit in range(8):
            if canvas.getpixel((xb * 8 + bit, y)):
                b |= 0x80 >> bit
        data.append(b)

out = '#pragma once\n\n'
out += '// Splash logo (128x64, 1 bit, MSB first) auto-generated by tools/gen_splash_logo.py\n\n'
out += '#include <Arduino.h>\n\n'
out += 'const unsigned char SplashLogo[] PROGMEM = {\n'
for i in range(0, len(data), 16):
    out += '  ' + ', '.join('0x%02X' % v for v in data[i:i + 16]) + ',\n'
out += '};\n'

out_path = os.path.join(project_dir, 'src', 'SplashLogo.h')
with open(out_path, 'w', encoding='utf-8') as f:
    f.write(out)

for y in range(H):
    print(''.join('#' if canvas.getpixel((x, y)) else '.' for x in range(0, W)))
print('wrote', out_path)
