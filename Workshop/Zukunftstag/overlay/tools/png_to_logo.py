"""Wandelt ein beliebiges Bild in ein 128x64 Schwarz/Weiss-Startlogo um (src/SplashLogo.h).

Aufruf:  python tools/png_to_logo.py bilder/mein_logo.png [--invert] [--threshold 128]
"""
import argparse
import os
import sys

from PIL import Image

W, H = 128, 64

parser = argparse.ArgumentParser()
parser.add_argument('image')
parser.add_argument('--invert', action='store_true', help='hell/dunkel vertauschen')
parser.add_argument('--threshold', type=int, default=128, help='Helligkeitsschwelle 0-255')
args = parser.parse_args()

project_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
if not os.path.exists(args.image):
    sys.exit('Bild nicht gefunden: ' + args.image)

src = Image.open(args.image).convert('RGBA')

# Transparente Bereiche werden schwarz (Display aus), sichtbare Pixel nach Helligkeit
bg = Image.new('RGBA', src.size, (0, 0, 0, 255))
bg.alpha_composite(src)
gray = bg.convert('L')

scale = min(W / gray.width, H / gray.height)
size = (max(1, round(gray.width * scale)), max(1, round(gray.height * scale)))
gray = gray.resize(size, Image.LANCZOS)

canvas = Image.new('1', (W, H), 0)
mask = gray.point(lambda v: 255 if v >= args.threshold else 0).convert('1')
if args.invert:
    mask = mask.point(lambda v: 255 - v)
canvas.paste(mask, ((W - size[0]) // 2, (H - size[1]) // 2))

data = bytearray()
for y in range(H):
    for xb in range(W // 8):
        b = 0
        for bit in range(8):
            if canvas.getpixel((xb * 8 + bit, y)):
                b |= 0x80 >> bit
        data.append(b)

out = '#pragma once\n\n'
out += '// Splash logo (128x64, 1 bit, MSB first) auto-generated by tools/png_to_logo.py\n\n'
out += '#include <Arduino.h>\n\n'
out += 'const unsigned char SplashLogo[] PROGMEM = {\n'
for i in range(0, len(data), 16):
    out += '  ' + ', '.join('0x%02X' % v for v in data[i:i + 16]) + ',\n'
out += '};\n'

out_path = os.path.join(project_dir, 'src', 'SplashLogo.h')
with open(out_path, 'w', encoding='utf-8') as f:
    f.write(out)

for y in range(0, H, 2):
    print(''.join('#' if canvas.getpixel((x, y)) else '.' for x in range(W)))
print('Geschrieben:', os.path.normpath(out_path))
